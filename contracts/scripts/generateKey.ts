import { ethers } from "ethers";
import * as fs from "fs";
import * as path from "path";

async function main() {
  console.log("==================================================");
  console.log("🔑 Synapse402 — Tempo L1 Wallet & Key Provisioner");
  console.log("==================================================");

  // Generate random cryptographic wallet
  const wallet = ethers.Wallet.createRandom();

  console.log("✅ New Tempo Wallet Generated:");
  console.log(`👤 Address:     ${wallet.address}`);
  console.log(`🔐 Private key stored in the ignored runtime env file.`);
  console.log("==================================================");

  // Keep generated credentials out of every source .env and archive. The
  // deployment config loads this ignored runtime file explicitly.
  const runtimeDir = path.join(__dirname, "../.runtime");
  fs.mkdirSync(runtimeDir, { recursive: true });
  const envPath = path.join(runtimeDir, "relayer.env");

  const envContent = `# Auto-generated by Synapse402 Provisioner
TEMPO_RPC_URL=https://rpc.moderato.tempo.xyz
TEMPO_CHAIN_ID=42431
PRIVATE_KEY=${wallet.privateKey}
TEMPO_RELAYER_KEY=${wallet.privateKey}
`;

  if (!fs.existsSync(envPath)) {
    fs.writeFileSync(envPath, envContent);
    console.log(`📄 Saved to: ${envPath}`);
  } else {
    console.log(`📄 Runtime key already exists: ${envPath}`);
  }

  console.log("==================================================");
  console.log("🚰 NEXT STEP: Fund this address on Tempo Moderato Testnet:");
  console.log(`   1. Copy address: ${wallet.address}`);
  console.log(`   2. Request testnet pathUSD or another supported TIP-20 fee token from the Tempo Faucet or Discord`);
  console.log(`   3. Run deployment: npm run deploy:tempo`);
  console.log("==================================================");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
